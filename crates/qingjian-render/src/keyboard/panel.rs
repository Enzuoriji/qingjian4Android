//! 键盘的几页。
//!
//! 一页一套布局、四行占满同一个高度——**页与页之间只有键换了，键盘本身不高不矮**，
//! 否则每切一次页都会把上面的应用内容顶一下（候选条固定高度就是为的这个）。

/// 键盘的一页。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Panel {
    /// 字母页。
    Letters,

    /// 数字与运算符页。
    Digits,

    /// 符号页。
    Symbols,

    /// 工具页：剪贴板这一类，以后的「震动程度」「设置」也排在这儿。
    ///
    /// 入口是候选条左边那个标（没组句时才画）——仿搜狗那个 S 的位置与用法。
    Tools,

    /// 剪贴板页：一屏 5 条复制过的文本，点一条插到光标处。
    Clipboard,

    /// 表情页：一屏十几个 emoji，点一个上屏。上面一条是分类标签。
    Emoji,

    /// 颜文字页：与 [`Panel::Emoji`] **同一个布局**，只是喂进来的那串字符换成了颜文字、
    /// 格子里画的是普通文字而不是彩色 emoji。所以这两页在 [`KeyboardLayout::of`] 里
    /// 指向同一份布局——共用的是一整套机制（命中、滚动、上屏），不是一个格子都没差。
    Kaomoji,
}

//! 键盘的几页。
//!
//! 一页一套布局、四行占满同一个高度——**页与页之间只有键换了，键盘本身不高不矮**，
//! 否则每切一次页都会把上面的应用内容顶一下（候选条固定高度就是为的这个）。

/// 键盘的一页。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Panel {
    /// 字母页。
    Letters,

    /// 数字与运算符页。
    Digits,

    /// 符号页。
    Symbols,

    /// 工具页：剪贴板这一类，以后的「震动程度」「设置」也排在这儿。
    ///
    /// 入口是候选条左边那个齿轮（没组句时才画）——仿搜狗那个 S 的位置与用法。
    Tools,

    /// 剪贴板页：一屏 6 条复制过的文本，点一条插到光标处。
    Clipboard,
}
